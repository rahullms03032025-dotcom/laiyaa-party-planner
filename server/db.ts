function ensureDb(): DatabaseSchema {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (!fs.existsSync(DB_FILE)) {
      fs.writeFileSync(DB_FILE, JSON.stringify(INITIAL_DB, null, 2), 'utf-8');
      return INITIAL_DB;
    }
    const content = fs.readFileSync(DB_FILE, 'utf-8');
    const parsed = JSON.parse(content) as DatabaseSchema;
    const validUsernames = ['rahul', 'ankur', 'yash', 'nityanand', 'ankita', 'priyanka', 'himani'];
    const hasInvalid = parsed.users?.some((u) => !validUsernames.includes(u.username));

    if (!parsed.users || parsed.users.length !== 7 || hasInvalid) {
      fs.writeFileSync(DB_FILE, JSON.stringify(INITIAL_DB, null, 2), 'utf-8');
      return INITIAL_DB;
    }

    // Ensure photos and messages are populated
    let modified = false;
    if (!Array.isArray(parsed.photos) || parsed.photos.length === 0) {
      parsed.photos = INITIAL_DB.photos;
      modified = true;
    }
    if (!Array.isArray(parsed.messages) || parsed.messages.length === 0) {
      parsed.messages = INITIAL_DB.messages;
      modified = true;
    }

    if (modified) {
      fs.writeFileSync(DB_FILE, JSON.stringify(parsed, null, 2), 'utf-8');
    }

    return parsed;
  } catch (err) {
    console.error('Error loading DB file, falling back to initial data:', err);
    return INITIAL_DB;
  }
}

export function getDb(): DatabaseSchema {
  return ensureDb();
}

export function saveDb(data: DatabaseSchema): void {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    fs.writeFileSync(DB_FILE, JSON.stringify(data, null, 2), 'utf-8');
  } catch (err) {
    console.error('Error saving DB file:', err);
  }
}

export function resetDbToDemo(): DatabaseSchema {
  saveDb(INITIAL_DB);
  return INITIAL_DB;
}
